def measure_text(text, scale=1, spacing=1, font=None):
    if font is not None:
        return int(font.measure(text))
    return len(str(text)) * (5 * scale + spacing)


def draw_text(canvas, text, x, y, color=None, scale=1, spacing=1, font=None):
    color = color or Color(235, 240, 250)
    if font is not None:
        return font.draw(canvas, text, x, y, color)
    cursor = int(x)
    for character in str(text):
        glyph = FONT.get(character.upper(), FONT["?"])
        for row, pattern in enumerate(glyph):
            for column, bit in enumerate(pattern):
                if bit == "1":
                    canvas.fill_rect(
                        Rect(cursor + column * scale, y + row * scale,
                             scale, scale), color)
        cursor += 5 * scale + spacing
    return cursor
